import { parseJson3Captions, withJson3Format } from "../src/lib/youtube";
import type { PageCaptionPayload, PageCaptionResultPayload, PageCaptionTrack } from "../src/types/transcript";

type RawTrack = {
  baseUrl?: string;
  languageCode?: string;
  name?: { simpleText?: string; runs?: Array<{ text?: string }> };
  kind?: string;
  vssId?: string;
};

type PlayerResponse = {
  videoDetails?: { videoId?: string; title?: string };
  captions?: {
    playerCaptionsTracklistRenderer?: { captionTracks?: RawTrack[] };
  };
};

const INNERTUBE_PLAYER_URL = "https://www.youtube.com/youtubei/v1/player?prettyPrint=false";
const ANDROID_CLIENT_VERSION = "20.10.38";

declare global {
  interface Window {
    ytInitialPlayerResponse?: PlayerResponse;
  }
}

type YouTubeWatchElement = HTMLElement & {
  playerData?: PlayerResponse;
};

function readPlayerResponse(): PlayerResponse | undefined {
  const watch = document.querySelector<YouTubeWatchElement>("ytd-watch-flexy");
  return watch?.playerData ?? window.ytInitialPlayerResponse;
}

function currentVideoId(): string | null {
  return new URL(location.href).searchParams.get("v");
}

function readCurrentPlayerResponse(): PlayerResponse | undefined {
  const response = readPlayerResponse();
  const videoId = currentVideoId();
  return videoId && response?.videoDetails?.videoId === videoId ? response : undefined;
}

function trackLabel(track: RawTrack): string {
  return track.name?.simpleText
    ?? track.name?.runs?.map((part) => part.text ?? "").join("")
    ?? track.languageCode
    ?? "Unknown";
}

function readCaptionTracks(response = readCurrentPlayerResponse()): PageCaptionTrack[] {
  const rawTracks = response?.captions?.playerCaptionsTracklistRenderer?.captionTracks ?? [];
  return rawTracks.flatMap((track, index) => {
    if (!track.baseUrl || !track.languageCode) return [];
    return [{
      id: track.vssId ?? `${track.languageCode}-${index}`,
      languageCode: track.languageCode,
      label: trackLabel(track),
      autoGenerated: track.kind === "asr",
      baseUrl: track.baseUrl,
    }];
  });
}

function rawCaptionTracks(response: PlayerResponse | undefined): RawTrack[] {
  return response?.captions?.playerCaptionsTracklistRenderer?.captionTracks ?? [];
}

async function readCaptionBody(baseUrl: string): Promise<unknown> {
  const response = await fetch(withJson3Format(baseUrl), { credentials: "omit" });
  if (!response.ok) throw new Error(`Caption request failed (${response.status}).`);
  const body = await response.text();
  if (!body.trim()) throw new Error("EMPTY_TIMEDTEXT_RESPONSE");
  try {
    return JSON.parse(body);
  } catch {
    throw new Error("YouTube returned an unsupported caption format.");
  }
}

async function fetchInnerTubePlayer(videoId: string): Promise<PlayerResponse> {
  const response = await fetch(INNERTUBE_PLAYER_URL, {
    method: "POST",
    credentials: "omit",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      context: {
        client: {
          clientName: "ANDROID",
          clientVersion: ANDROID_CLIENT_VERSION,
          androidSdkVersion: 34,
          hl: "en",
          gl: "US",
        },
      },
      videoId,
    }),
  });
  if (!response.ok) throw new Error(`YouTube player request failed (${response.status}).`);
  return await response.json() as PlayerResponse;
}

function chooseInnerTubeTrack(tracks: RawTrack[], requested: PageCaptionTrack): RawTrack | undefined {
  return tracks.find((track) => track.vssId === requested.id)
    ?? tracks.find((track) => track.languageCode === requested.languageCode && (track.kind === "asr") === requested.autoGenerated)
    ?? tracks.find((track) => track.languageCode === requested.languageCode);
}

async function loadCaptionSegments(track: PageCaptionTrack): Promise<ReturnType<typeof parseJson3Captions>> {
  try {
    return parseJson3Captions(await readCaptionBody(track.baseUrl));
  } catch (error) {
    if (!(error instanceof Error) || error.message !== "EMPTY_TIMEDTEXT_RESPONSE") throw error;
  }

  const videoId = currentVideoId();
  if (!videoId) throw new Error("Could not identify the current YouTube video.");
  const innerTubePlayer = await fetchInnerTubePlayer(videoId);
  const fallbackTrack = chooseInnerTubeTrack(rawCaptionTracks(innerTubePlayer), track);
  if (!fallbackTrack?.baseUrl) throw new Error("YouTube did not return an accessible caption track.");
  return parseJson3Captions(await readCaptionBody(fallbackTrack.baseUrl));
}

function publishTracks(): boolean {
  const videoId = currentVideoId();
  if (!videoId) {
    window.postMessage({
      source: "ezscribe-page-bridge",
      type: "CAPTION_TRACKS",
      videoId: null,
      title: document.title.replace(/\s+-\s+YouTube$/, ""),
      tracks: [],
    } satisfies PageCaptionPayload, location.origin);
    return true;
  }

  const response = readCurrentPlayerResponse();
  if (!response) return false;
  const tracks = readCaptionTracks(response);

  const payload: PageCaptionPayload = {
    source: "ezscribe-page-bridge",
    type: "CAPTION_TRACKS",
    videoId,
    title: response.videoDetails?.title ?? document.title.replace(/\s+-\s+YouTube$/, ""),
    tracks: tracks.map(({ baseUrl: _baseUrl, ...track }) => track),
  };
  window.postMessage(payload, location.origin);
  return true;
}

async function publishCaptions(trackId: string, requestId: string): Promise<void> {
  const track = readCaptionTracks().find((candidate) => candidate.id === trackId);
  if (!track) {
    const payload: PageCaptionResultPayload = {
      source: "ezscribe-page-bridge",
      type: "CAPTION_RESULT",
      requestId,
      error: "Caption track is no longer available.",
    };
    window.postMessage(payload, location.origin);
    return;
  }

  try {
    const segments = await loadCaptionSegments(track);
    if (segments.length === 0) throw new Error("This caption track did not contain readable segments.");
    const payload: PageCaptionResultPayload = {
      source: "ezscribe-page-bridge",
      type: "CAPTION_RESULT",
      requestId,
      segments,
    };
    window.postMessage(payload, location.origin);
  } catch (error) {
    const payload: PageCaptionResultPayload = {
      source: "ezscribe-page-bridge",
      type: "CAPTION_RESULT",
      requestId,
      error: error instanceof Error ? error.message : "Could not load captions for this video.",
    };
    window.postMessage(payload, location.origin);
  }
}

export default defineContentScript({
  matches: ["https://www.youtube.com/*"],
  world: "MAIN",
  runAt: "document_idle",
  main() {
    let publishGeneration = 0;
    const publishWhenReady = () => {
      const generation = ++publishGeneration;
      const delays = [0, 100, 250, 500, 1_000, 2_000, 4_000];
      for (const delay of delays) {
        window.setTimeout(() => {
          if (generation !== publishGeneration) return;
          if (publishTracks()) publishGeneration++;
        }, delay);
      }
    };
    const request = (event: MessageEvent) => {
      if (event.source !== window || event.data?.source !== "ezscribe-extension") return;
      if (event.data?.type === "REQUEST_CAPTION_TRACKS") publishWhenReady();
      if (event.data?.type === "REQUEST_CAPTIONS" && typeof event.data.trackId === "string" && typeof event.data.requestId === "string") {
        void publishCaptions(event.data.trackId, event.data.requestId);
      }
    };

    window.addEventListener("message", request);
    window.addEventListener("yt-navigate-finish", publishWhenReady);
    publishWhenReady();
  },
});
