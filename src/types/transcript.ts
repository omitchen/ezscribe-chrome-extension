export type CaptionTrack = {
  id: string;
  languageCode: string;
  label: string;
  autoGenerated: boolean;
};

export type CaptionSegment = {
  startMs: number;
  durationMs: number;
  text: string;
};

export type VideoContext = {
  videoId: string | null;
  title: string | null;
  tracks: CaptionTrack[];
};

export type ExtensionRequest =
  | { type: "GET_VIDEO_CONTEXT" }
  | { type: "GET_CAPTIONS"; trackId: string }
  | { type: "SEEK_TO"; seconds: number };

export type ExtensionResponse =
  | { ok: true; context: VideoContext }
  | { ok: true; segments: CaptionSegment[] }
  | { ok: true }
  | { ok: false; error: string };

export type PageCaptionTrack = CaptionTrack & {
  baseUrl: string;
};

export type PageCaptionPayload = {
  source: "ezscribe-page-bridge";
  type: "CAPTION_TRACKS";
  videoId: string | null;
  title: string | null;
  tracks: CaptionTrack[];
};

export type PageCaptionResultPayload = {
  source: "ezscribe-page-bridge";
  type: "CAPTION_RESULT";
  requestId: string;
  segments?: CaptionSegment[];
  error?: string;
};

export type PageBridgePayload = PageCaptionPayload | PageCaptionResultPayload;
